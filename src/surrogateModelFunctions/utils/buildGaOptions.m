function gaOptions = buildGaOptions(options)
%BUILDGAOPTIONS Create genetic algorithm options.

gaOptions = optimoptions('ga', ...
    'OutputFcn', @gaDebugLogger, ...
    'Display', 'iter', ...
    'PlotFcn', {@gaplotbestf, @gaplotscores, @gaplotstopping}, ...
    'PopulationSize', options.populationSize, ...
    'MaxGenerations', options.maxGen, ...
    'MaxStallGenerations', options.maxStallGen, ...
    'FunctionTolerance', options.funTol, ...
    'UseParallel', options.parallel);
end
