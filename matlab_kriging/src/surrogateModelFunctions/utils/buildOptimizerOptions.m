function opts = buildOptimizerOptions(options)
    % Extract parameters from options and assing to opts (fmincon default)
    algo    = getOpt(options, 'fminconAlgorithm', 'sqp');
    optTol  = getOpt(options, 'fminconOptTol', 1e-6);
    stepTol = getOpt(options, 'fminconStepTol', 1e-6);
    maxIter = getOpt(options, 'fminconMaxIter', 500);
    display = getOpt(options, 'fminconDisplay', 'off');

    opts = optimoptions('fmincon', ...
        'Algorithm', algo, ...
        'SpecifyObjectiveGradient', true, ... % Keep to true
        'OptimalityTolerance', optTol, ...
        'StepTolerance', stepTol, ...
        'Display', display, ...
        'MaxIterations', maxIter);
end
